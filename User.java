class User {
    String name;
    int chips;
    int currentBet;

    public String getName() {
        return name;
    }

    public int getChips() {
        return chips;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setChips(int chips) {
        this.chips = chips;
    }

    public int getCurrentBet() {
        return currentBet;
    }

    public void setCurrentBet(int currentBet) {
        this.currentBet = currentBet;
    }
}